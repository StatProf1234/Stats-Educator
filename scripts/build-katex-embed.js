// One-off build script (run manually, not part of any automated build —
// this project has no build step) that produces
// vendor/katex/katex-embedded.js: the same rules as katex.min.css, but
// with every @font-face's woff2 inlined as a base64 data URI instead of
// a relative fonts/*.woff2 path. Re-run this whenever vendor/katex is
// upgraded to a new version.
//
// Why this exists: the Ctrl+Alt+D "download current view" feature
// (app.js's downloadCurrentView()) needs KaTeX's real CSS to render
// formulas properly, but can't get it at runtime via fetch() or
// document.styleSheets[].cssRules — both throw/fail when the site is
// opened as file://. Loading a <script src="..."> tag doesn't have
// that restriction, so baking the CSS (fonts and all) into a JS file
// that just assigns a global string sidesteps the problem entirely.
//
// Usage: node scripts/build-katex-embed.js

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CSS_PATH = path.join(ROOT, 'vendor/katex/katex.min.css');
const FONTS_DIR = path.join(ROOT, 'vendor/katex/fonts');
const OUT_PATH = path.join(ROOT, 'vendor/katex/katex-embedded.js');

let css = fs.readFileSync(CSS_PATH, 'utf8');

css = css.replace(/@font-face\{([^}]*)\}/g, (block, body) => {
  const family = /font-family:([^;]+);/.exec(body)?.[1];
  const style = /font-style:([^;]+);/.exec(body)?.[1];
  const weight = /font-weight:([^;]+);/.exec(body)?.[1];
  const woff2Name = /url\(fonts\/([^)]+\.woff2)\)/.exec(body)?.[1];
  if (!family || !woff2Name) return block;

  const fontPath = path.join(FONTS_DIR, woff2Name);
  const b64 = fs.readFileSync(fontPath).toString('base64');
  return `@font-face{font-family:${family};font-style:${style};font-weight:${weight};src:url(data:font/woff2;base64,${b64}) format("woff2")}`;
});

const out = `// Generated by scripts/build-katex-embed.js — do not edit by hand.
// Self-contained copy of katex.min.css with fonts inlined as data URIs,
// loaded on demand by app.js's downloadCurrentView() (Ctrl+Alt+D).
window.KATEX_EMBEDDED_CSS = ${JSON.stringify(css)};
`;

fs.writeFileSync(OUT_PATH, out);
console.log(`Wrote ${OUT_PATH} (${(out.length / 1024).toFixed(0)} KB)`);
